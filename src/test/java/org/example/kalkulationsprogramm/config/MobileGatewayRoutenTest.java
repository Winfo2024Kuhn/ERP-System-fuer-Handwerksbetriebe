package org.example.kalkulationsprogramm.config;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

import tools.jackson.databind.DeserializationFeature;
import tools.jackson.databind.ObjectMapper;
import tools.jackson.databind.ObjectReader;
import tools.jackson.databind.json.JsonMapper;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.regex.Pattern;
import org.junit.jupiter.api.Test;
import tools.jackson.core.JacksonException;

/**
 * Das öffentliche Handy-Gateway (deployment/mobile-public) lässt nur die Routen aus
 * {@code mobile-routes.conf} durch. Die Datei wird von {@code sync_routes.py} aus
 * {@link MobileApiPolicy} erzeugt; dieser Test hält beide Listen gleich, damit eine neue
 * Handy-Route nicht still am Gateway mit 404 endet (so geschehen nach #211).
 */
class MobileGatewayRoutenTest {
    private static final Path GATEWAY_ROUTEN = Path.of("deployment", "mobile-public", "mobile-routes.conf");
    private static final Path GATEWAY_VORLAGE = Path.of("deployment", "mobile-public", "nginx.conf.template");
    private static final Path GATEWAY_SERVER = Path.of("deployment", "mobile-public", "mobile-server.conf");
    /** Fester Eintrag für die PWA-Oberfläche selbst, kein API-Pfad; muss zu render() in sync_routes.py passen. */
    private static final String PWA_OBERFLAECHE = "GET:/zeiterfassung(?:/.*)?";
    private static final Pattern WEITERLEITUNG = Pattern.compile("\\b(?:proxy|grpc|fastcgi|uwsgi|scgi)_pass\\b");
    private static final ObjectReader JSON_TEXT = JsonMapper.builderWithJackson2Defaults().build().readerFor(String.class)
            .with(DeserializationFeature.FAIL_ON_TRAILING_TOKENS);

    @Test
    void gatewayLaesstGenauDieRoutenAusMobileApiPolicyDurch() throws IOException {
        List<String> erwartet = new ArrayList<>();
        erwartet.add(PWA_OBERFLAECHE);
        erwartet.addAll(MobileApiPolicy.routenFuerGateway());

        assertThat(gatewayRouten(Files.readAllLines(GATEWAY_ROUTEN)))
                .as("mobile-routes.conf weicht von MobileApiPolicy ab. Neu erzeugen mit "
                        + "'python3 deployment/mobile-public/sync_routes.py' und den Diff prüfen.")
                .containsExactlyElementsOf(erwartet);
    }

    /**
     * Die Routenliste schützt nur, solange alles andere gesperrt bleibt. Die Proxy-Tests mit Docker
     * laufen nicht in der CI; dieser Textabgleich fängt ein {@code default 1;}, ein zusätzliches
     * {@code include} oder einen Weiterleitungsblock ohne Sperre trotzdem ab.
     */
    @Test
    void gatewaySperrtAllesAusserhalbDerRoutenliste() throws IOException {
        String vorlage = Files.readString(GATEWAY_VORLAGE);
        assertThat(blockRumpf(vorlage.lines().toList(), "map \"$mobile_method:$uri\" $mobile_allowed {"))
                .containsExactly("default 0;", "include /etc/nginx/mobile-routes.conf;");
        assertThat(vorlage.split("mobile-routes\\.conf", -1)).as("mobile-routes.conf nur einmal eingebunden").hasSize(2);

        List<String> server = Files.readAllLines(GATEWAY_SERVER);
        assertThat(server.get(0)).isEqualTo("if ($ambiguous_path) { return 400; }");
        List<String> weiterleitung = blockRumpf(server, "location / {");
        assertThat(weiterleitung.get(0)).isEqualTo("if ($mobile_allowed = 0) { return 404; }");
        assertThat(weiterleitung).contains("proxy_pass http://erp;");
        assertThat(server.stream().filter(zeile -> WEITERLEITUNG.matcher(zeile).find()))
                .as("nur der gesperrte Block leitet weiter").hasSize(1);
    }

    @Test
    void liestErzeugteZeilenUndIgnoriertKommentare() {
        List<String> zeilen = List.of(
                "# Generated by sync_routes.py from MobileApiPolicy.java. Do not edit.",
                "\"~^GET:/api/kunden$\" 1;",
                "",
                "\"~^POST:/api/notiz/\\\"x\\\\y$\" 1;");

        assertThat(gatewayRouten(zeilen)).containsExactly("GET:/api/kunden", "POST:/api/notiz/\"x\\y");
    }

    @Test
    void unbekannteZeileLaesstDenAbgleichScheitern() {
        assertThatThrownBy(() -> gatewayRouten(List.of("\"~^GET:/api/kunden$\" 0;")))
                .isInstanceOf(IllegalArgumentException.class);
        assertThatThrownBy(() -> gatewayRouten(List.of("\"GET:/api/kunden\" 1;")))
                .isInstanceOf(IllegalArgumentException.class);
        assertThatThrownBy(() -> gatewayRouten(List.of("\"~^GET:/api/kunden$ 1;")))
                .isInstanceOf(IllegalArgumentException.class);
        assertThatThrownBy(() -> gatewayRouten(List.of("\"~^GET:/api/kunden$\" \"~^GET:/api/admin$\" 1;")))
                .isInstanceOf(IllegalArgumentException.class);
    }

    /** Wandelt {@code "~^GET:/pfad$" 1;} in {@code GET:/pfad}; alles Unbekannte bricht ab. */
    private static List<String> gatewayRouten(List<String> zeilen) {
        List<String> routen = new ArrayList<>();
        for (String zeile : zeilen) {
            if (zeile.isBlank() || zeile.startsWith("#")) {
                continue;
            }
            if (!zeile.endsWith(" 1;")) {
                throw new IllegalArgumentException("Unbekannte Zeile in mobile-routes.conf: " + zeile);
            }
            String eintrag = jsonText(zeile.substring(0, zeile.length() - " 1;".length()));
            if (!eintrag.startsWith("~^") || !eintrag.endsWith("$")) {
                throw new IllegalArgumentException("Route ohne ~^…$ in mobile-routes.conf: " + zeile);
            }
            routen.add(eintrag.substring(2, eintrag.length() - 1));
        }
        return routen;
    }

    /** Zeilen zwischen {@code kopf} und der schließenden Klammer, ohne Einrückung. */
    private static List<String> blockRumpf(List<String> zeilen, String kopf) {
        List<String> bereinigt = zeilen.stream().map(String::strip).toList();
        int start = bereinigt.indexOf(kopf);
        assertThat(start).as("Block '%s' fehlt", kopf).isNotNegative();
        int ende = bereinigt.subList(start, bereinigt.size()).indexOf("}");
        assertThat(ende).as("Block '%s' nicht geschlossen", kopf).isPositive();
        return bereinigt.subList(start + 1, start + ende);
    }

    private static String jsonText(String literal) {
        try {
            return JSON_TEXT.readValue(literal);
        } catch (JacksonException e) {
            throw new IllegalArgumentException("Kein gültiger Eintrag in mobile-routes.conf: " + literal, e);
        }
    }
}
