-- Abgleich der ERP-Kontakte ins Telefonbuch der FRITZ!Box.
--
-- WARUM
-- Das ERP legt in der FRITZ!Box ein eigenes Telefonbuch „ERP-Kontakte“ an und hält es aktuell
-- (Kunden, Lieferanten, Mitarbeiter, Steuerberater). Damit nur Geänderte gesendet, Neue
-- angelegt und Weggefallene gelöscht werden, merkt sich das ERP je Kontakt, welcher Eintrag
-- in der Box zu ihm gehört und was zuletzt gesendet wurde.
--
-- WAS
--   telefonbuch_zuordnung.quelle_typ       Art des Kontakts (KUNDE, LIEFERANT, MITARBEITER, …)
--   telefonbuch_zuordnung.quelle_id        ID des Kontakts in seiner Tabelle (kein Fremdschlüssel:
--                                          gelöschte Kontakte müssen hier bleiben, bis ihr Eintrag
--                                          in der Box gelöscht ist)
--   telefonbuch_zuordnung.eintrag_id       Kennung (UniqueID) des Eintrags in der FRITZ!Box
--   telefonbuch_zuordnung.inhalt_hash      SHA-256 des zuletzt gesendeten Inhalts (Name + Nummern)
--   telefonbuch_zuordnung.gesendet_am      Zeitpunkt der letzten Übertragung
-- Die ID des Telefonbuchs, der Schalter und der Stand liegen in system_setting (telefon.telefonbuch.*).
--
-- ROBUSTHEIT
-- CREATE TABLE IF NOT EXISTS (die Eindeutigkeit steckt als Constraint in der Tabelle), ein zweiter Lauf ändert nichts.

CREATE TABLE IF NOT EXISTS telefonbuch_zuordnung (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quelle_typ  VARCHAR(40)  NOT NULL,
    quelle_id   BIGINT       NOT NULL,
    eintrag_id  VARCHAR(20)  NOT NULL,
    inhalt_hash VARCHAR(64)  NOT NULL,
    gesendet_am TIMESTAMP(6) NOT NULL,
    CONSTRAINT telefonbuch_zuordnung__quelle UNIQUE (quelle_typ, quelle_id)
);
