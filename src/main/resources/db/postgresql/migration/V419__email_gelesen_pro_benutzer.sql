-- E-Mails: "gelesen" gilt pro Person.
--
-- WARUM
-- Bisher hatte jede Mail genau ein Feld "gelesen" fuer alle. Oeffnete der Chef eine neue Mail,
-- war sie fuer alle Kollegen gelesen - und deren Benachrichtigungs-Glocke meldete sie nie.
-- Jetzt merkt sich das Programm fuer jeden Benutzer einzeln, welche Mails er gelesen hat.
--
-- WAS
--   email_gelesen: ein Eintrag je Benutzer und gelesener Mail. Gesendete Mails gelten immer als
--   gelesen und bekommen keinen Eintrag. Das alte Feld email.is_read bleibt und heisst nur noch
--   "irgendwer hat sie schon geoeffnet".
--
-- UEBERNAHME
-- Was heute schon gelesen ist (is_read), bleibt fuer alle bisherigen Benutzer gelesen - sonst
-- stuenden alle ploetzlich vor Tausenden "neuen" Mails. Ungelesene Mails bleiben fuer alle
-- ungelesen. Neue Benutzer bekommen beim Anlegen alle vorhandenen Mails als gelesen.
--
-- ROBUSTHEIT
-- Tabelle und Index nur, wenn sie fehlen. Die Uebernahme laeuft nur, solange die Tabelle noch
-- leer ist - ein zweiter Lauf aendert nichts. Wird ein Benutzer oder eine Mail geloescht,
-- verschwinden die Eintraege mit (ON DELETE CASCADE).

CREATE TABLE IF NOT EXISTS email_gelesen (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    benutzer_id BIGINT NOT NULL,
    email_id BIGINT NOT NULL,
    gelesen_am TIMESTAMP(6) NOT NULL,
    CONSTRAINT uk_email_gelesen_benutzer_email UNIQUE (benutzer_id, email_id),
    CONSTRAINT fk_email_gelesen_benutzer FOREIGN KEY (benutzer_id) REFERENCES frontend_user_profile (id) ON DELETE CASCADE,
    CONSTRAINT fk_email_gelesen_email FOREIGN KEY (email_id) REFERENCES email (id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_email_gelesen_email ON email_gelesen (email_id);

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM email_gelesen) THEN
        INSERT INTO email_gelesen (benutzer_id, email_id, gelesen_am)
        SELECT b.id, e.id, COALESCE(e.first_viewed_at, CURRENT_TIMESTAMP)
        FROM frontend_user_profile b
        CROSS JOIN email e
        WHERE e.is_read = TRUE
          AND e.direction = 'IN'
        ON CONFLICT (benutzer_id, email_id) DO NOTHING;
    END IF;
END $$;
