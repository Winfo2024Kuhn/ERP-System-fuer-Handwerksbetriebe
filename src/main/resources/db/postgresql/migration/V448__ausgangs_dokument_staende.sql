-- Versionsverlauf für Ausgangsdokumente (Angebot, AB, Rechnung …): „Stände wie bei git“.
--
-- WARUM
--   Der Editor speichert alle 10 Sekunden. Ein Verlauf jeder Speicherung wäre unlesbar. Ein Stand
--   entsteht deshalb nur, wenn das Dokument das Haus verlässt (Drucken, als PDF speichern,
--   E-Mail: POST /api/ausgangs-dokumente/{id}/pdf-speichern bzw. .../{id}/staende/festhalten) und
--   sich der Inhalt seit dem letzten Stand geändert hat. Ältere Stände lassen sich ansehen und zurückholen.
--   Die GoBD-Quelle bleibt ausgangs_geschaeftsdokument_audit mit seiner Hash-Kette; die Stände
--   sind die lesbare Fassung für den Betrieb.
--
-- WAS
--   ausgangs_dokument_stand               ein festgehaltener Inhalt je Export (art EXPORT) bzw. vor dem
--                                         Zurückholen eines älteren Stands (art VOR_WIEDERHERSTELLEN).
--                                         nummer läuft je Dokument ab 1. aenderungen = JSON-Array der
--                                         Änderungssätze gegenüber dem vorigen Stand, bearbeitet_von_ids =
--                                         JSON-Array der Benutzer, die seitdem gespeichert haben.
--                                         inhalt_fingerabdruck = SHA-256 des verglichenen Inhalts.
--                                         pdf_dateiname = das beim Export gespeicherte PDF im Upload-Ordner.
--   ausgangs_dokument_offene_bearbeitung  wer seit dem letzten Stand gespeichert bzw. einen Stand
--                                         zurückgeholt hat; wird beim nächsten Stand übernommen und geleert.
--   ausgangs_geschaeftsdokument.wiederherstellungs_zaehler  siehe unten.
--
-- LÖSCHEN
--   Stände werden nie geändert oder gelöscht (einzige Ausnahme: ein ohne PDF festgehaltener Stand
--   bekommt pdf_dateiname nachgetragen, wenn derselbe Inhalt später mit PDF exportiert wird). Nur der Hard-Delete eines Entwurfs nimmt sie über
--   ON DELETE CASCADE mit (der GoBD-Audit bleibt). Wird ein Benutzer gelöscht, bleibt sein Stand
--   ohne Namen stehen (festgehalten_von_id → NULL); seine offene Bearbeitung verschwindet.
--
-- ALTBESTAND
--   Vorhandene Dokumente haben noch keinen Stand. Der erste Export nach dem Update legt Stand 1
--   „Erste Fassung“ an.
--
-- ROBUSTHEIT
--   CREATE ... IF NOT EXISTS, Fremdschlüssel inline - ein zweiter Lauf ändert nichts.

CREATE TABLE IF NOT EXISTS ausgangs_dokument_stand (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dokument_id BIGINT NOT NULL,
    nummer INTEGER NOT NULL,
    art VARCHAR(30) NOT NULL,
    festgehalten_am TIMESTAMP(6) NOT NULL,
    festgehalten_von_id BIGINT,
    bearbeitet_von_ids TEXT,
    aenderungen TEXT,
    wiederhergestellt_aus_nummer INTEGER,
    inhalt_fingerabdruck CHAR(64) NOT NULL,
    pdf_dateiname VARCHAR(255),
    betreff VARCHAR(500),
    datum DATE,
    betrag_netto NUMERIC(12,2),
    mwst_satz NUMERIC(5,4),
    zahlungsziel_tage INTEGER,
    rechnungsadresse_override VARCHAR(500),
    positionen_json TEXT,
    html_inhalt TEXT,
    CONSTRAINT uk_ausgangs_dokument_stand_nummer UNIQUE (dokument_id, nummer),
    CONSTRAINT fk_ausgangs_dokument_stand_dokument FOREIGN KEY (dokument_id)
        REFERENCES ausgangs_geschaeftsdokument (id) ON DELETE CASCADE,
    CONSTRAINT fk_ausgangs_dokument_stand_benutzer FOREIGN KEY (festgehalten_von_id)
        REFERENCES frontend_user_profile (id) ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS ausgangs_dokument_offene_bearbeitung (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dokument_id BIGINT NOT NULL,
    benutzer_id BIGINT NOT NULL,
    seit TIMESTAMP(6) NOT NULL,
    wiederhergestellt_aus_nummer INTEGER,
    wiederhergestellt_am TIMESTAMP(6),
    CONSTRAINT uk_ausgangs_dokument_offene_bearbeitung UNIQUE (dokument_id, benutzer_id),
    CONSTRAINT fk_ausgangs_dokument_offene_bearbeitung_dokument FOREIGN KEY (dokument_id)
        REFERENCES ausgangs_geschaeftsdokument (id) ON DELETE CASCADE,
    CONSTRAINT fk_ausgangs_dokument_offene_bearbeitung_benutzer FOREIGN KEY (benutzer_id)
        REFERENCES frontend_user_profile (id) ON DELETE CASCADE
);

-- Wiederherstellungs-Zähler am Dokument: Nur das Zurückholen eines Stands erhöht ihn. Ein Editor
-- schickt beim Speichern den Wert mit, den er kennt; weicht er ab, wird nicht gespeichert (409),
-- damit ein veralteter Editor (z. B. auf einem zweiten Gerät) den zurückgeholten Inhalt nicht überschreibt.
ALTER TABLE ausgangs_geschaeftsdokument ADD COLUMN IF NOT EXISTS wiederherstellungs_zaehler INTEGER NOT NULL DEFAULT 0;
