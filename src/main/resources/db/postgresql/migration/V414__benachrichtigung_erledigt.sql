-- Erledigte Einträge der Benachrichtigungs-Glocke, pro Benutzer.
--
-- WARUM
-- Bisher hat sich nur der Browser gemerkt, was in der Glocke weggeklickt wurde (teils nur bis
-- zum Schließen des Tabs). Neuer Tab, anderer PC oder ein kurz aus der Liste gerutschter
-- Eintrag – und alles war wieder da. Jetzt merkt sich der Server, was ein Benutzer erledigt hat,
-- und lässt es schon beim Zählen weg.
--
-- WAS
--   benachrichtigung_erledigt: ein Eintrag je Benutzer und Glocken-Eintrag. "schluessel" ist
--   Art und Kennung des Eintrags, z. B. 'TERMIN:123' oder 'MONATSABSCHLUSS:2026-09'.
--   "erledigt_am" entscheidet, ob ein Dauer-Hinweis (überfällige Rechnung, offener Antrag …)
--   nach einer Woche wieder erinnert.
--
-- ROBUSTHEIT
-- Tabelle und Index nur, wenn sie fehlen – mehrfaches Ausführen ändert nichts. Wird ein
-- Benutzer gelöscht, verschwinden seine Einträge mit (ON DELETE CASCADE).

CREATE TABLE IF NOT EXISTS benachrichtigung_erledigt (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    benutzer_id BIGINT NOT NULL,
    schluessel VARCHAR(120) NOT NULL,
    erledigt_am TIMESTAMP(6) NOT NULL,
    CONSTRAINT uk_benachrichtigung_erledigt_benutzer_schluessel UNIQUE (benutzer_id, schluessel),
    CONSTRAINT fk_benachrichtigung_erledigt_benutzer FOREIGN KEY (benutzer_id) REFERENCES frontend_user_profile (id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_benachrichtigung_erledigt_am ON benachrichtigung_erledigt (erledigt_am);
